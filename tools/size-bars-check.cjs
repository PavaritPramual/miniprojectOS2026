const assert = require("node:assert/strict");
const { buildSizeBars } = require("../static/size-bars.js");
const item = (relativePath, allocatedBytes) => ({ relativePath, name: relativePath, kind: "file", allocatedBytes });
const mixed = buildSizeBars([item("unknown", null), item("zero", 0), item("small", 10), item("large", 90)], 100);
assert.deepEqual(mixed.rows.map(r => r.item.name), ["large", "small", "zero"]);
assert.equal(mixed.unknownCount, 1);
assert.equal(mixed.rows[0].share, 90);
assert.equal(mixed.rows[0].width, 100);
assert.equal(mixed.rows[2].width, 0);
assert.equal(buildSizeBars([item("x", 10)], null).rows[0].share, null);
assert.equal(buildSizeBars([item("zero", 0)], 0).rows[0].share, null);
assert.equal(buildSizeBars([item("unknown", null)], null).rows.length, 0);
assert.equal(buildSizeBars([], 0).rows.length, 0);
const many = Array.from({ length: 60 }, (_, i) => item(`file-${i}`, i));
assert.deepEqual(buildSizeBars(many, 1770).rows.map(r => r.item.allocatedBytes), [59,58,57,56,55,54,53,52,51,50]);
assert.equal(buildSizeBars([item("a", Infinity),item("b",-1),item("c",Number.MAX_SAFE_INTEGER+1)], null).unknownCount, 3);
const tied = buildSizeBars([item("ไทย.txt", 1), item("a.txt",1)], 2);
assert.deepEqual(tied.rows.map(r => r.item.name), buildSizeBars([item("a.txt",1),item("ไทย.txt",1)],2).rows.map(r => r.item.name));
console.log("PASS: sorted top 10, percentages, zero vs unknown, pending totals, empty folders, Unicode and invalid sizes");
